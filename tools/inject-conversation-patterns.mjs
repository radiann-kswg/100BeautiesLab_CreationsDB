const raw = fs.readFileSync(DB_PATH, 'utf8');
const arr = JSON.parse(raw);

let updated = 0;
let skipped = 0;

for (const rec of arr) {
  if (!rec || typeof rec !== 'object' || rec.Num == null) continue;
  if (!(rec.Num in patterns)) continue;

  if (rec.ConversationPattern) {
    console.log(`[SKIP] Num ${rec.Num}: ConversationPattern already exists`);
    skipped++;
    continue;
  }

  rec.ConversationPattern = patterns[rec.Num];
  console.log(`[ADD]  Num ${rec.Num}: ConversationPattern added (${rec.ConversationPattern.DialogueExamples.length} examples)`);
  updated++;
}

fs.writeFileSync(DB_PATH, JSON.stringify(arr, null, 2), 'utf8');
console.log(`\n完了: ${updated} 件追加, ${skipped} 件スキップ`);
